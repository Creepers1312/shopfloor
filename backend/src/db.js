"use strict";
const { Pool } = require("pg");
const config = require("./config");

const pool = new Pool({ ...config.db, max: 10, idleTimeoutMillis: 30000 });
pool.on("error", (err) => console.error("[db] Verbindungsfehler im Pool:", err.message));

const SCHEMA = `
CREATE TABLE IF NOT EXISTS meta (
  key   text PRIMARY KEY,
  value jsonb NOT NULL
);
INSERT INTO meta (key, value) VALUES ('revision', '0'::jsonb) ON CONFLICT (key) DO NOTHING;

-- Die drei Dokumente der Oberfläche. "users" hat hier nur die Revision,
-- die Konten selbst liegen in der Tabelle users.
CREATE TABLE IF NOT EXISTS documents (
  name       text PRIMARY KEY CHECK (name IN ('state', 'settings', 'users')),
  value      jsonb,
  revision   bigint NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by text
);
INSERT INTO documents (name) VALUES ('state'), ('settings'), ('users') ON CONFLICT (name) DO NOTHING;

CREATE TABLE IF NOT EXISTS users (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       text NOT NULL,
  role       text NOT NULL DEFAULT '',
  perm       text NOT NULL DEFAULT 'editor' CHECK (perm IN ('admin', 'editor', 'viewer')),
  disabled   boolean NOT NULL DEFAULT false,
  pw_hash    text,
  last_login timestamptz,
  extra      jsonb NOT NULL DEFAULT '{}'::jsonb,
  dashboard  jsonb,
  position   integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS users_name_lower ON users (lower(name));

-- Sitzungen verweisen bewusst nur über den Namen auf das Konto (kein Fremdschlüssel),
-- damit eine Wiederherstellung der Tabelle users angemeldete Geräte nicht abmeldet.
CREATE TABLE IF NOT EXISTS sessions (
  token_hash text PRIMARY KEY,
  user_name  text,
  demo       boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_expires ON sessions (expires_at);

-- Inaktivität: wann die Sitzung zuletzt benutzt wurde (Abmeldung nach SESSION_IDLE_HOURS)
ALTER TABLE sessions ADD COLUMN IF NOT EXISTS last_seen timestamptz NOT NULL DEFAULT now();

-- Sicherheitsprotokoll: Anmeldungen, Konten, Sicherungen, Speichervorgänge
CREATE TABLE IF NOT EXISTS audit_log (
  id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at        timestamptz NOT NULL DEFAULT now(),
  user_name text,
  ip        text,
  action    text NOT NULL,
  detail    jsonb NOT NULL DEFAULT '{}'::jsonb,
  count     integer NOT NULL DEFAULT 1
);
CREATE INDEX IF NOT EXISTS audit_log_at ON audit_log (at DESC);

-- Anmeldename und E-Mail (eindeutig ohne Groß-/Kleinschreibung); Anzeigename bleibt "name"
ALTER TABLE users ADD COLUMN IF NOT EXISTS username text;
ALTER TABLE users ADD COLUMN IF NOT EXISTS email text;
CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower ON users (lower(username)) WHERE username IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower ON users (lower(email)) WHERE email IS NOT NULL;

-- „Passwort vergessen“: Einmal-Links (nur der Hash des Tokens) und Anfragen an die Administration
CREATE TABLE IF NOT EXISTS password_resets (
  token_hash text PRIMARY KEY,
  user_name  text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL
);
CREATE TABLE IF NOT EXISTS reset_requests (
  user_name  text PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  ip         text
);

CREATE TABLE IF NOT EXISTS backups (
  filename   text PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  kind       text NOT NULL,
  note       text,
  ok         boolean NOT NULL,
  size_bytes bigint NOT NULL DEFAULT 0,
  error      text
);
`;

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function waitForDb(attempts = 30) {
  for (let i = 1; i <= attempts; i++) {
    try {
      await pool.query("SELECT 1");
      return;
    } catch (err) {
      if (i === attempts) throw err;
      console.log(`[db] Datenbank noch nicht erreichbar (${i}/${attempts}): ${err.message}`);
      await sleep(2000);
    }
  }
}

async function migrate() {
  // Advisory-Lock: mehrere API-Instanzen migrieren nie gleichzeitig
  const c = await pool.connect();
  try {
    await c.query("SELECT pg_advisory_lock(424242)");
    await c.query(SCHEMA);
    // Ältere Konten ohne Anmeldenamen bekommen einen aus dem Namen
    const n = await require("./users").backfillUsernames(c);
    if (n) console.log(`[db] ${n} Anmeldename(n) aus dem Namen abgeleitet`);
  } finally {
    await c.query("SELECT pg_advisory_unlock(424242)").catch(() => {});
    c.release();
  }
}

async function tx(fn) {
  const c = await pool.connect();
  try {
    await c.query("BEGIN");
    const result = await fn(c);
    await c.query("COMMIT");
    return result;
  } catch (err) {
    await c.query("ROLLBACK").catch(() => {});
    throw err;
  } finally {
    c.release();
  }
}

async function getRevision(q = pool) {
  const r = await q.query("SELECT (value #>> '{}')::bigint AS rev FROM meta WHERE key = 'revision'");
  return Number(r.rows[0] ? r.rows[0].rev : 0);
}

// Sperrt den Revisionszähler bis zum Ende der Transaktion (serialisiert alle Schreibvorgänge)
async function lockRevision(c) {
  const r = await c.query("SELECT (value #>> '{}')::bigint AS rev FROM meta WHERE key = 'revision' FOR UPDATE");
  return Number(r.rows[0].rev);
}

// Erhöht den Zähler und markiert die genannten Dokumente als geändert
async function bumpRevision(c, docNames, by) {
  const r = await c.query(
    "UPDATE meta SET value = to_jsonb((value #>> '{}')::bigint + 1) WHERE key = 'revision' RETURNING (value #>> '{}')::bigint AS rev"
  );
  const rev = Number(r.rows[0].rev);
  if (docNames && docNames.length) {
    await c.query(
      "UPDATE documents SET revision = $1, updated_at = now(), updated_by = $2 WHERE name = ANY($3::text[])",
      [rev, by || null, docNames]
    );
  }
  return rev;
}

async function getMeta(key, q = pool) {
  const r = await q.query("SELECT value FROM meta WHERE key = $1", [key]);
  return r.rows[0] ? r.rows[0].value : null;
}
async function setMeta(key, value, q = pool) {
  await q.query(
    "INSERT INTO meta (key, value) VALUES ($1, $2::jsonb) ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value",
    [key, JSON.stringify(value)]
  );
}

module.exports = { pool, waitForDb, migrate, tx, getRevision, lockRevision, bumpRevision, getMeta, setMeta };
